use std::{
    any::Any,
    sync::atomic::{AtomicUsize, Ordering},
};

/// Numeric identifier for a component type, assigned at runtime.
pub type ComponentTypeId = usize;

/// Maximum number of distinct component types the ECS can support.
///
/// Backed by a [`fixedbitset::FixedBitSet`] of this capacity, so raising the
/// limit requires a recompile. Registering more than `MAX_COMPONENTS` component
/// types will panic at runtime with a descriptive message.
pub const MAX_COMPONENTS: usize = 32;

/// Allocates unique [`ComponentTypeId`]s from an isolated counter.
///
/// The default production path uses a process-global instance via
/// [`get_next_component_type_id`]. Tests that need to exercise boundary
/// conditions (e.g. registering exactly [`MAX_COMPONENTS`] types) can create a
/// fresh `ComponentRegistry` with a zeroed counter.
pub struct ComponentRegistry {
    next_id: AtomicUsize,
}

impl ComponentRegistry {
    /// Creates a new registry with the counter starting at zero.
    pub const fn new() -> Self {
        Self { next_id: AtomicUsize::new(0) }
    }

    /// Allocates and returns the next unique [`ComponentTypeId`].
    ///
    /// Panics if the number of allocated IDs would exceed [`MAX_COMPONENTS`].
    pub fn allocate_id(&self) -> usize {
        let id = self.next_id.fetch_add(1, Ordering::Relaxed);
        assert!(
            id < MAX_COMPONENTS,
            "component type ID {id} exceeds the maximum of {MAX_COMPONENTS} components. \
             Increase MAX_COMPONENTS in component_signature.rs and component.rs to support more."
        );
        id
    }
}

/// Process-global registry used by `#[derive(Component)]`.
static GLOBAL_REGISTRY: ComponentRegistry = ComponentRegistry::new();

/// Allocates and returns the next unique `ComponentTypeId` from the global registry.
///
/// Called once per component type, typically from the code generated by the
/// `#[derive(Component)]` macro. Panics if the total number of registered
/// component types would exceed [`MAX_COMPONENTS`].
pub fn get_next_component_type_id() -> usize {
    GLOBAL_REGISTRY.allocate_id()
}

/// Marker trait that all ECS components must implement.
///
/// In practice you should derive this trait with `#[derive(Component)]` from
/// the `rust_ecs::derive` module, which generates the `get_type_id` impl and
/// the `as_any` helpers automatically.
pub trait Component {
    /// Returns the unique `ComponentTypeId` assigned to this component type.
    fn get_type_id() -> usize
    where
        Self: Sized;

    /// Returns `self` as `&dyn Any` for downcasting.
    fn as_any(&self) -> &dyn Any;

    /// Returns `self` as `&mut dyn Any` for downcasting.
    fn as_any_mut(&mut self) -> &mut dyn Any;
}

#[cfg(test)]
mod tests {
    use super::{ComponentRegistry, MAX_COMPONENTS};

    #[test]
    fn max_components_boundary() {
        let registry = ComponentRegistry::new();
        for _ in 0..MAX_COMPONENTS {
            registry.allocate_id();
        }
    }

    #[test]
    #[should_panic]
    fn max_components_exceeded_panics() {
        let registry = ComponentRegistry::new();
        for _ in 0..=MAX_COMPONENTS {
            registry.allocate_id();
        }
    }
}
